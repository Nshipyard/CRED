export type SourceKind = 'statcan' | 'boc' | 'cer';

export function sourceName(source: SourceKind): string {
  if (source === 'statcan') return 'Statistics Canada';
  if (source === 'cer') return 'Canada Energy Regulator';
  return 'Bank of Canada';
}

export type CategorySlug =
  | 'money-banking-finance'
  | 'population-employment-labour'
  | 'national-accounts'
  | 'production-business-activity'
  | 'energy'
  | 'prices'
  | 'housing-construction'
  | 'international-trade-investment'
  | 'provinces-territories-cities';

export interface SeriesMeta {
  id: string;
  title: string;
  source: SourceKind;
  sourceLabel: string;
  tableId?: string;
  vectorIds?: number[];
  // Optional per-vector weights applied before combining component vectors.
  // A trade balance maps to [exportsVector, importsVector] with [1, -1].
  vectorWeights?: number[];
  valetGroup?: string;
  valetSeriesKey?: string;
  units: string;
  unitsDetail?: string;
  frequency: 'Daily' | 'Weekly' | 'Monthly' | 'Quarterly' | 'Annual';
  category: CategorySlug;
  release: string;
  releaseUrl: string;
  sourceUrl: string;
  description: string;
  featured?: boolean;
  lastVerified: string;
  // Set for pipeline-ingested series (see scripts/ingest/); hand-curated entries omit it.
  autoGenerated?: boolean;
  // Raw StatCan English label for pipeline-ingested series (e.g.
  // "Canada;Housing starts;Single-detached"). Kept for provenance and as a
  // search alias; the display title is the FRED-style rewrite.
  originalTitle?: string;
  // Map view: series in the same geoFamily share a choropleth toggle.
  geoFamily?: 'unemployment-by-province' | 'cpi-by-province' | 'gdp-by-province';
}

