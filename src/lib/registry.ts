/* ---- Helpers expected by the app (derived from the verified SERIES list) ---- */

import { GENERATED_SERIES } from './registry.generated';
import { ENERGY_GENERATED_SERIES } from './registry.energy';

// Full registry: hand-curated entries plus pipeline-generated ones (macro
// subjects and the subject-25 energy run). Curated entries keep priority in
// search ranking (see searchSeries).
export const REGISTRY: SeriesMeta[] = [
  ...SERIES,
  ...GENERATED_SERIES,
  ...ENERGY_GENERATED_SERIES,
];

export const CATEGORY_LABELS: Record<CategorySlug, string> = Object.fromEntries(
  CATEGORIES.map((c) => [c.slug, c.title])
) as Record<CategorySlug, string>;

export function getSeries(id: string): SeriesMeta | undefined {
  return REGISTRY.find((s) => s.id === id);
}

export function searchSeries(q: string): SeriesMeta[] {
  const needle = q.trim().toLowerCase();
  if (!needle) return SERIES;
  // Ranked: featured first, then hand-curated title matches, curated other-field
  // matches, generated title matches, generated other-field matches. Within a
  // tier, title-prefix matches come first, then shorter titles, then A-Z.
  // Curated entries keep priority so flagship queries ("inflation",
  // "unemployment", "GDP", "housing") still return the hand-verified series first.
  const hits: { s: SeriesMeta; tier: number; prefix: number }[] = [];
  for (const s of REGISTRY) {
    const titleLc = s.title.toLowerCase();
    const inTitle = titleLc.includes(needle);
    const other =
      s.id.toLowerCase().includes(needle) ||
      s.description.toLowerCase().includes(needle) ||
      (s.originalTitle ?? '').toLowerCase().includes(needle) ||
      s.release.toLowerCase().includes(needle) ||
      s.frequency.toLowerCase().includes(needle) ||
      s.sourceLabel.toLowerCase().includes(needle) ||
      s.units.toLowerCase().includes(needle) ||
      (s.unitsDetail ?? '').toLowerCase().includes(needle);
    if (!inTitle && !other) continue;
    const curated = !s.autoGenerated;
    const tier = s.featured ? 0 : curated ? (inTitle ? 1 : 2) : inTitle ? 3 : 4;
    hits.push({ s, tier, prefix: titleLc.startsWith(needle) ? 0 : 1 });
  }
  hits.sort(
    (a, b) =>
      a.tier - b.tier ||
      a.prefix - b.prefix ||
      a.s.title.length - b.s.title.length ||
      a.s.title.localeCompare(b.s.title)
  );
  return hits.map((h) => h.s);
}

